const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch()
  const p = await (await b.newContext({ viewport: { width: 1500, height: 950 }, deviceScaleFactor: 2 })).newPage()
  await p.goto('http://127.0.0.1:8010/#/records', { waitUntil: 'networkidle' })
  await p.waitForTimeout(2600)
  await p.screenshot({ path: '../docs/_shots/fixed-records.png' })
  await p.goto('http://127.0.0.1:8010/#/write', { waitUntil: 'networkidle' })
  await p.waitForTimeout(2600)
  await p.click('.cm-content')
  await p.keyboard.type('今天的对话让我意识到，我一直在用忙碌来回避某些情绪。')
  await p.waitForTimeout(2600)
  await p.screenshot({ path: '../docs/_shots/fixed-write.png' })
  await b.close()
})()
